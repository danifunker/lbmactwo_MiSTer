#!/usr/bin/env python3
"""Filter gen/cpu_tests.h into a variant corpus header with some tests removed.

The CPU corpus is compiled *into* the bench payload (bench_main.c and
macos_bench/cpu_bench.c include it), so excluding a test at build time
means dropping its entry from g_cpu_tests[] before the compiler sees it,
not skipping it at run time.

Selection is by test name, because that is the only classification the
generated header carries for exception vectors: mame_cpu_capture.lua
names every exception test "... (vec N / $XX)". Group 0 on the 68020
(M68020UM Table 6-1) is vectors 0-3: reset SSP/PC, bus error, address
error.

Usage:
    filter_cpu_tests_h.py --exclude-group0 -o out.h gen/cpu_tests.h
    filter_cpu_tests_h.py --exclude-vec 3,10 -o out.h gen/cpu_tests.h
    filter_cpu_tests_h.py --exclude-name 'Line A' -o out.h gen/cpu_tests.h

CPU_TEST_MAX_PRELOAD / CPU_TEST_MAX_TEST are left as the source header
declared them: they are upper bounds, so keeping them is always valid
(at worst a few unused bytes per entry) while recomputing them risks
under-sizing an array the filter kept.
"""

import argparse
import re
import sys

ARRAY_OPEN = "static CpuTestSpec g_cpu_tests[] = {"
ARRAY_CLOSE = "};"
ENTRY_START = re.compile(r'^    \{"((?:[^"\\]|\\.)*)",')
VEC_IN_NAME = re.compile(r"vec (\d+)")


def split_entries(lines):
    """Return (head, entries, tail) where entries is a list of line-lists."""
    try:
        open_idx = next(i for i, l in enumerate(lines) if l.rstrip("\n") == ARRAY_OPEN)
    except StopIteration:
        sys.exit(f"could not find '{ARRAY_OPEN}' — is this a cpu_tests.h?")

    close_idx = None
    entries = []
    current = None
    for i in range(open_idx + 1, len(lines)):
        line = lines[i]
        if line.rstrip("\n") == ARRAY_CLOSE:
            close_idx = i
            break
        if ENTRY_START.match(line):
            if current is not None:
                entries.append(current)
            current = [line]
        elif current is not None:
            current.append(line)
        else:
            sys.exit(f"line {i + 1}: content before the first test entry")
    if current is not None:
        entries.append(current)
    if close_idx is None:
        sys.exit("unterminated g_cpu_tests[] initializer")
    return lines[: open_idx + 1], entries, lines[close_idx:]


def entry_name(entry):
    return ENTRY_START.match(entry[0]).group(1)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("header", help="input cpu_tests.h")
    ap.add_argument("-o", "--output", required=True, help="output header path")
    ap.add_argument("--exclude-group0", action="store_true",
                    help="drop 68020 group 0 exception tests (vectors 0-3)")
    ap.add_argument("--exclude-vec", default="",
                    help="comma-separated exception vector numbers to drop")
    ap.add_argument("--exclude-name", action="append", default=[],
                    help="drop tests whose name matches this regex (repeatable)")
    args = ap.parse_args()

    vecs = set()
    if args.exclude_group0:
        vecs |= {0, 1, 2, 3}
    if args.exclude_vec:
        vecs |= {int(v) for v in args.exclude_vec.split(",") if v.strip()}
    name_res = [re.compile(p) for p in args.exclude_name]
    if not vecs and not name_res:
        sys.exit("nothing to exclude: pass --exclude-group0, --exclude-vec, or --exclude-name")

    def excluded(name):
        m = VEC_IN_NAME.search(name)
        if m and int(m.group(1)) in vecs:
            return True
        return any(r.search(name) for r in name_res)

    with open(args.header) as f:
        lines = f.readlines()

    head, entries, tail = split_entries(lines)
    kept, dropped = [], []
    for e in entries:
        (dropped if excluded(entry_name(e)) else kept).append(e)

    if not kept:
        sys.exit("filter removed every test — refusing to write an empty corpus")

    banner = [
        "/* FILTERED COPY -- generated by gen/filter_cpu_tests_h.py.\n",
        " * Do not edit by hand; regenerate from gen/cpu_tests.h.\n",
        f" * Source: {args.header}\n",
        f" * Excluded {len(dropped)} of {len(entries)} tests:\n",
    ]
    banner += [f" *   {entry_name(e)}\n" for e in dropped]
    banner.append(" */\n")

    with open(args.output, "w") as f:
        f.writelines(banner)
        f.writelines(head)
        for e in kept:
            f.writelines(e)
        f.writelines(tail)

    print(f"Wrote {args.output}: {len(kept)} tests kept, {len(dropped)} dropped")
    for e in dropped:
        print(f"  - {entry_name(e)}")


if __name__ == "__main__":
    main()
