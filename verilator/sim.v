	// CPU debug outputs
	output [31:0] debug_pc,
	output [15:0] debug_opcode,
	output        debug_fetch_valid,
	output  [2:0] debug_fc,           // Function code (2=supv program, 1=supv data, etc)
	output        debug_write_valid,  // Write bus cycle completed
	output [31:0] debug_write_addr,   // Write address
	output [15:0] debug_write_data,   // Write data
	output        debug_cirrd_valid,  // FPU CIR read cycle completed (FC=7, $22000-$2203F)
	output [31:0] debug_cirrd_addr,   // CIR read address
	output [15:0] debug_cirrd_data,   // CIR read data (as seen by the CPU)

	// RAM debug outputs
	output [24:0] debug_ram_addr,
	output [15:0] debug_ram_din,
	output [15:0] debug_ram_dout,
	output        debug_ram_we,
	output        debug_ram_oe,
	output  [1:0] debug_ram_ds,
	output        debug_selectRAM,
	output        debug_selectROM,

	// Peripheral debug outputs
	output        debug_selectVIA,
	output        debug_selectNuBus,
	output        debug_selectSCSI,
	output        debug_selectSCC,
	output        debug_selectIWM,
	output        debug_selectASC,
	output        debug_memoryOverlayOn,
	output [31:0] debug_cpuAddr,
	output [15:0] debug_cpuDataIn,    // Data from CPU to peripherals
	output [15:0] debug_cpuDataOut,   // Data from peripherals to CPU
	output        debug_cpuRW,        // 1=read, 0=write
	output        debug_cpuBusControl,
	output        debug_viaRd,        // VIA read enable (VMA-synchronized)
	output        debug_viaWr,        // VIA write enable (VMA-synchronized)
	output        debug_cpuAS,        // CPU AS signal (active low)
	output        debug_cpuVMA,       // VMA signal (active low)
	output        debug_cpuVPA,       // VPA signal (active low)
	output        debug_cpuDTACK,     // DTACK signal (active low)
	output        debug_cpuUDS,       // UDS signal (active low)
	output        debug_cpuLDS,       // LDS signal (active low)
	output        debug_selectVIA2,
	output        debug_berr,
	output [31:0] debug_vbr,
	output  [2:0] debug_cpuIPL,

	// berr-rerun investigation (2026-07-12): format-$B RTE / berr_inhibit
	output        debug_berr_inhibit,   // TG68 rerun window active
	output [31:0] debug_berr_data,      // berr_data_buf re-fed during the window
	output        debug_busev_valid,    // one pulse per completed CPU bus cycle
	output [31:0] debug_busev_addr,
	output [15:0] debug_busev_data,     // word the CPU RECEIVED (reads) / drove (writes)
	output        debug_busev_rw,       // 1=read
	output  [2:0] debug_busev_fc,

	// Serial terminal interface
	output        serial_txd,       // SCC Channel A TX output (for sim-side RX)
	input         serial_rxd,       // SCC Channel A RX input (from sim-side TX)

	// Machine configuration inputs
	input  [1:0]  cfg_cpuType,      // 00=FX68K, 01/10/11=TG68K variants
	input  [1:0]  cfg_memSize       // RAM size: 00=1MB, 01=2MB, 10=4MB, 11=8MB
);

	localparam SCSI_DEVS = 2;

	// Configuration - directly from inputs (Mac II)
	wire [1:0] status_mem = cfg_memSize;     // RAM size (matches FPGA status[5:4])
	wire [1:0] status_cpu = cfg_cpuType;     // CPU type (must use TG68K 68030 mode)
	// Mac II: 31.3344 MHz system clock (2 × C15M), CPU at 15.6672 MHz via clk16_en.
	// Sim plusarg +cpu8 lets us test whether boot divergence is CPU/bus pacing.
	wire      status_turbo = !$test$plusargs("cpu8");
	////////////////////   CLOCKS   ///////////////////

	// Clock generation (clk_sys is 31.3344 MHz from testbench, matching FPGA PLL)
	wire clk_mem = clk_sys;  // Use same clock for memory
	wire pll_locked = !reset;

	// Clock enables - generated by addrController_top
	wire clk8_en_p, clk8_en_n;
	wire clk16_en_p, clk16_en_n;
	wire clk8;
	
	// Generate clk_sys enable (one tick per cycle at 31.3344 MHz)
	reg clk32_en_p, clk32_en_n;
	always @(posedge clk_sys) clk32_en_p <= 1'b1;
	always @(negedge clk_sys) clk32_en_n <= 1'b1;

	// Reset logic
	// NOTE: Do NOT include _cpuReset_o here! The RESET instruction drives
	// reset_n low to reset peripherals, but should NOT reset the CPU itself.
	// IMPORTANT: In simulation, wait for ROM download to complete before releasing reset
	reg n_reset = 0;
	reg n_reset_prev = 0;
	reg dio_download_prev = 0;
	always @(posedge clk_sys) begin
		reg [15:0] rst_cnt;

		if (clk8_en_p) begin
			n_reset_prev <= n_reset;
			dio_download_prev <= dio_download;

			// Debug: track when download completes
			if (dio_download_prev && !dio_download) begin
				$display("SIM: dio_download went LOW - ROM download complete");
			end

			if(~pll_locked || reset || dio_download) begin
				rst_cnt <= '1;
				n_reset <= 0;
			end
			else if(rst_cnt) begin
				rst_cnt <= rst_cnt - 1'd1;
				// Debug: show countdown progress every 0x1000 cycles
				if (rst_cnt[11:0] == 12'h000) begin
					$display("SIM: rst_cnt=%04x n_reset=%b", rst_cnt, n_reset);
				end
			end
			else begin
				n_reset <= 1;
			end

			// Debug: track when n_reset changes
			if (n_reset != n_reset_prev) begin
				$display("SIM: *** n_reset changed to %b *** (rst_cnt=%04x)", n_reset, rst_cnt);
			end
		end
	end

	///////////////////////////////////////////////////

	wire nubus_ce_pixel;
	assign CE_PIXEL  = nubus_ce_pixel;

	// Video Output - Mac II NuBus video system
	// nubus_blank is active-high DE (1 = visible pixels, 0 = blanked)
	// VGA_HB/VGA_VB need active-high blanking (1 = blanked), so invert
	assign VGA_R  = nubus_r;
	assign VGA_G  = nubus_g;
	assign VGA_B  = nubus_b;
	wire VGA_DE = nubus_blank;
	assign VGA_VS = nubus_vsync;
	assign VGA_HS = nubus_hsync;
	assign VGA_HB = ~nubus_blank;
	assign VGA_VB = ~nubus_blank;

	wire [15:0] asc_audio_l, asc_audio_r;
	assign AUDIO_L = asc_audio_l;
	assign AUDIO_R = asc_audio_r;

	// Mac II memory configuration
	localparam configROMSize = 2'b10;  // 256K ROM
	wire [1:0] configRAMSize = cfg_memSize; // RAM size from --ram (00=1MB,01=2MB,10=4MB,11=8MB)

	// Serial Ports — connected to serial terminal in sim_main.cpp
	wire serialOut;              // SCC Channel A TX (driven by SCC)
	wire serialIn = serial_rxd; // SCC Channel A RX (driven by sim)
	wire serialCTS = 1'b0;
	wire serialRTS;
	assign serial_txd = serialOut;

	// NuBus Video system wires
	wire [15:0] nubusDataOut_card;
	wire nubusAck_card;
	wire nubus_irq_n;

	// NuBus arbiter: handles empty-slot bus errors (see nubus_arbiter.sv)
	wire [15:0] nubusDataOut;
	wire nubusAck;
	wire nubus_acked_arb;
	wire nubus_berr;

	nubus_arbiter nubus_arb (
		.clk(clk_sys),
		._cpuAS(_cpuAS),
		.cpuAddr(cpuAddr),
		.selectNuBus(selectNuBus),
		.card_data_out(nubusDataOut_card),
		.card_ack_n(nubusAck_card),
		.data_out(nubusDataOut),
		.ack_n(nubusAck),
		.acked(nubus_acked_arb),
		.berr(nubus_berr)
	);
	wire [7:0] nubus_r, nubus_g, nubus_b;
	wire nubus_hsync, nubus_vsync, nubus_blank;
	wire selectNuBus;

	// interconnects
	// CPU
	wire _cpuReset, _cpuReset_o, _cpuUDS, _cpuLDS, _cpuRW, _cpuAS;
	wire _cpuVMA, _cpuVPA, _cpuDTACK;
	wire E_rising, E_falling;
	wire [2:0] _cpuIPL;
	wire [2:0] cpuFC;
	wire [7:0] cpuAddrHi;
	wire [31:0] cpuAddr;
	wire [15:0] cpuDataOut;

	// RAM/ROM
	wire _romOE;
	wire _ramOE, _ramWE;
	wire _memoryUDS, _memoryLDS;
	wire videoBusControl;
	wire dioBusControl;
	wire cpuBusControl;
	wire [22:0] memoryAddr;	// 23-bit byte address (8MB max RAM)
	wire [15:0] memoryDataOut;
	wire memoryLatch;
	wire capslock;
	
	// peripherals
	wire vid_alt, loadPixels, pixelOut, _hblank, _vblank, hsync, vsync;
	wire memoryOverlayOn, selectSCSI, selectSCSIDMA, scsiDREQ, selectSCC, selectIWM, selectVIA, selectVIA2, selectRAM, selectROM, selectSEOverlay, selectASC;
	wire [1:0] glueRAMSize;
	wire [15:0] dataControllerDataOut;

	// MC68881 FPU coprocessor cycles use FC=7 CPU space, cpID=1.
	// The Verilator harness uses a fast CIR-level responder for boot/debug runs.
	wire fpuAddrMatch = (cpuFC == 3'b111) && (cpuAddr[31:16] == 16'h0002) && (cpuAddr[15:13] == 3'b001);
	wire selectFPU = fpuAddrMatch && !_cpuAS;
	wire [31:0] fpu_data_out;
	wire fpu_dsack0_n, fpu_dsack1_n;
	wire fpu_sense_n;

	// floppy disk image interface
	wire dskReadAckInt;
	wire [21:0] dskReadAddrInt;
	wire dskReadAckExt;
	wire [21:0] dskReadAddrExt;

	// dtack generation in turbo mode
	reg  turbo_dtack_en, cpuBusControl_d;
	always @(posedge clk_sys) begin
		if (!_cpuReset) begin
			turbo_dtack_en <= 0;
		end
		else begin
			cpuBusControl_d <= cpuBusControl;
			if (_cpuAS) turbo_dtack_en <= 0;
			if (!_cpuAS & ((!cpuBusControl_d & cpuBusControl) | (!selectROM & !selectRAM))) turbo_dtack_en <= 1;
		end
	end

	// VPA: assert for FC=7 autovector cycles, except FPU coprocessor cycles.
	wire viaAccess = selectVIA | selectVIA2;
	assign      _cpuVPA = (cpuFC == 3'b111 && !selectFPU) ? 1'b0 :
	                      viaAccess ? ~!_cpuAS :
	                      ~(!_cpuAS && cpuAddr[23:21] == 3'b111);
	wire sim_ram_dtack = (~(!_cpuAS && cpuAddr[23:21] != 3'b111) | (status_turbo & !turbo_dtack_en));
	// DTACK: FPU uses DSACK; VIA accesses use VPA/VMA synchronous handshake.
	assign      _cpuDTACK = selectFPU ? (eff_fpu_dsack0_n & eff_fpu_dsack1_n) :
	                        selectNuBus ? nubusAck :
	                        selectSCSIDMA ? ~scsiDREQ :
	                        viaAccess ? 1'b1 :
	                        sim_ram_dtack;

	// Bus error timeout — undecoded addresses trigger bus error after ~8us
	reg [8:0] berr_counter;
	reg berr_out;
	wire nubus_acked = nubus_acked_arb;  // from nubus_arbiter: card or empty-slot responded
	wire scsi_dma_wait = selectSCSIDMA && !scsiDREQ;
	wire any_select = selectRAM | selectROM | selectVIA | selectVIA2 | selectSCC
	                | (selectSCSI && !scsi_dma_wait) | selectIWM | selectASC | nubus_acked | selectSEOverlay | selectFPU;
	wire is_cpu_space = (cpuFC == 3'b111);

	always @(posedge clk_sys) begin
		if (!_cpuReset) begin
			berr_counter <= 0;
			berr_out <= 0;
		end else begin
			if (_cpuAS) begin
				berr_counter <= 0;
				berr_out <= 0;
			end else if (berr_out) begin
				// Hold BERR until AS deasserts (CPU ends bus cycle)
			end else if (is_cpu_space || any_select)
				berr_counter <= 0;
			else if (berr_counter == 9'd251)  // ~8us at 31.3344 MHz sys clock
				begin berr_out <= 1; berr_counter <= 0; end
			else
				berr_counter <= berr_counter + 1'd1;
		end
	end
	// Mac II: C15M = 15.6672 MHz CPU (status_turbo=1 selects clk16_en from 31.3344 MHz sys clock)
	wire        cpu_en_p      = status_turbo ? clk16_en_p : clk8_en_p;
	wire        cpu_en_n      = status_turbo ? clk16_en_n : clk8_en_n;
	assign      _cpuReset_o   = tg68_reset_n;
	assign      _cpuRW        = tg68_rw;
	assign      _cpuAS        = tg68_as_n;
	assign      _cpuUDS       = tg68_uds_n;
	assign      _cpuLDS       = tg68_lds_n;
	assign      E_falling     = tg68_E_falling;
	assign      E_rising      = tg68_E_rising;
	assign      _cpuVMA       = tg68_vma_n;
	assign      cpuFC[0]      = tg68_fc0;
	assign      cpuFC[1]      = tg68_fc1;
	assign      cpuFC[2]      = tg68_fc2;
	// Mac II HMMU: translate CPU address when VIA2 PB3 is driven low.
	// FC=7 (CPU space / coprocessor CIR) bypasses translation.
	wire        hmmu_active;
	wire [31:0] cpuAddr_xlated;
	hmmu u_hmmu(.addr_in(tg68_a), .active(hmmu_active), .addr_out(cpuAddr_xlated));
	assign      cpuAddr       = (cpuFC == 3'b111) ? tg68_a : cpuAddr_xlated;
	assign      cpuDataOut    = tg68_dout;

	// tg68k wire declarations
	wire        tg68_rw;
	wire        tg68_as_n;
	wire        tg68_uds_n;
	wire        tg68_lds_n;
	wire        tg68_E_rising;
	wire        tg68_E_falling;
	wire        tg68_vma_n;
	wire        tg68_fc0;
	wire        tg68_fc1;
	wire        tg68_fc2;
	wire [15:0] tg68_dout;
	wire [31:0] tg68_a;
	wire        tg68_reset_n;
	wire        tg68_longword;

	tg68k tg68k_inst (
		.clk        ( clk_sys      ),
		.reset      ( !_cpuReset   ),
		.phi1       ( cpu_en_p     ),
		.phi2       ( cpu_en_n     ),
		.cpu        ( 2'b11        ), // 68020 mode (cpu(0) must be 1 for VBR support)

		.dtack_n    ( _cpuDTACK    ),
		.rw_n       ( tg68_rw      ),
		.as_n       ( tg68_as_n    ),
		.uds_n      ( tg68_uds_n   ),
		.lds_n      ( tg68_lds_n   ),
		.fc         ( { tg68_fc2, tg68_fc1, tg68_fc0 } ),
		.reset_n    ( tg68_reset_n ),

		.E          (              ),
		.E_div      ( status_turbo ),
		.E_PosClkEn ( tg68_E_falling ),
		.E_NegClkEn ( tg68_E_rising  ),
		.vma_n      ( tg68_vma_n   ),
		.vpa_n      ( _cpuVPA      ),

		.br_n       ( 1'b1         ),
		.bg_n       (              ),
		.bgack_n    ( 1'b1         ),

		.ipl        ( _cpuIPL      ),
		.berr       ( berr_effective ),
		.cpu_halted (              ),
		.din        ( cpu_data_in  ),
		.dout       ( tg68_dout    ),
		.longword   ( tg68_longword ),
		.addr       ( tg68_a       ),
		.VBR_out    ( debug_vbr    ),
		.berr_inhibit ( cpu_berr_inhibit ),
		.berr_data    ( cpu_berr_data    )
	);

	// Format $B RTE: when berr_inhibit is active, suppress bus errors
	// and provide the data input buffer value from the exception frame
	wire cpu_berr_inhibit;
	wire [31:0] cpu_berr_data;
	wire berr_effective = cpu_berr_inhibit ? 1'b0 : berr_out;
	reg [15:0] fpu_data_hold;
	reg fpu_data_hold_valid;
	always @(posedge clk_sys) begin
		if (!_cpuReset) begin
			fpu_data_hold <= 16'h0000;
			fpu_data_hold_valid <= 1'b0;
		end else if (!_cpuAS && selectFPU && _cpuRW) begin
			fpu_data_hold <= fpu_d_to_cpu;
			fpu_data_hold_valid <= 1'b1;
		end else if (!_cpuAS && !selectFPU) begin
			fpu_data_hold_valid <= 1'b0;
		end
	end

	wire [15:0] cpu_data_in = cpu_berr_inhibit ? cpu_berr_data[15:0] :
	                          selectFPU ? fpu_d_to_cpu :
	                          fpu_data_hold_valid ? fpu_data_hold :
	                          dataControllerDataOut;

	// CIR register address remapping (mirrors LBMacTwo.sv):
	//   Standard reg 0 (Response) -> mc68881_top reg 13
	//   Standard reg 2 (Save)     -> mc68881_top reg 12
	//   Standard reg 3 (Restore)  -> mc68881_top reg 28
	wire [4:0] fpu_addr_remapped = (cpuAddr[5:1] == 5'd0) ? 5'd13 :
	                               (cpuAddr[5:1] == 5'd2) ? 5'd12 :
	                               (cpuAddr[5:1] == 5'd3) ? 5'd28 :
	                               cpuAddr[5:1];

	// -------------------- 16-bit ↔ 32-bit FPU bus adapter -----------------
	// Ported from SingleStepTests/cpu_fpu/cpu_fpu_tests.v. TG68K has a
	// 16-bit data bus and splits .L into 2 word transfers; mc68881_top's
	// Operand CIR is a 32-bit register and expects ONE transfer per
	// long-word (per AN-947 / M68020 PRM §9):
	//   - WRITES (CPU→FPU): latch the first 16-bit half into fpu_wr_hi.
	//     Suppress cs_n on the first half (FPU sees nothing) and fake a
	//     DSACK back to TG68K. On the second half, drive
	//     d_in = {fpu_wr_hi, cpuDataOut} as a single 32-bit transfer and
	//     let the FPU's DSACK pass through.
	//   - READS (FPU→CPU): on the first half, let the FPU strobe normally
	//     and latch the full 32-bit d_out into fpu_rd_latch. TG68K gets
	//     the HIGH word. On the second half, suppress cs_n (FPU doesn't
	//     advance), fake DSACK, return the LOW half from the latch.
	// Non-Operand CIR accesses pass through unchanged (16-bit semantics).
	wire fpu_is_operand_cycle = (fpu_addr_remapped == 5'd8);
	reg        fpu_xfer_phase;   // 0 = first half (HIGH), 1 = second half (LOW)
	reg [15:0] fpu_wr_hi;
	reg [31:0] fpu_rd_latch;
	reg        fpu_prev_as_for_phase;
	// Flip phase on the END of each FPU operand bus cycle (AS-rising edge
	// while addressed at operand) so phase is stable throughout each cycle.
	wire fpu_bus_end_edge = fpuAddrMatch && fpu_is_operand_cycle
	                        && _cpuAS && !fpu_prev_as_for_phase;
	always @(posedge clk_sys) begin
		if (!_cpuReset) begin
			fpu_xfer_phase        <= 1'b0;
			fpu_wr_hi             <= 16'h0000;
			fpu_rd_latch          <= 32'h0000_0000;
			fpu_prev_as_for_phase <= 1'b1;
		end else begin
			fpu_prev_as_for_phase <= _cpuAS;
			// Capture at the END of each access (AS-rising edge), when the
			// FPU has just dsacked and data is valid. Latches simultaneously
			// with the phase flip.
			if (fpu_bus_end_edge && fpu_xfer_phase == 1'b0) begin
				if (!_cpuRW) fpu_wr_hi    <= cpuDataOut;
				else         fpu_rd_latch <= fpu_data_out;
			end
			if (fpu_bus_end_edge)
				fpu_xfer_phase <= ~fpu_xfer_phase;
		end
	end

	// WRITES: FPU active on phase=1 (second half); READS: active on phase=0.
	wire fpu_active_phase = _cpuRW ? !fpu_xfer_phase : fpu_xfer_phase;
	wire fpu_cs_n_eff = fpu_is_operand_cycle
	                    ? ~(fpuAddrMatch && fpu_active_phase)
	                    : ~fpuAddrMatch;
	wire [31:0] fpu_d_in_eff = (fpu_is_operand_cycle && !_cpuRW)
	                           ? {fpu_wr_hi, cpuDataOut}
	                           : {16'h0000, cpuDataOut};
	// TG68K-side DSACK: fake during the inactive phase, pass-through during
	// the active phase.
	wire fpu_inactive_phase_act = fpuAddrMatch && fpu_is_operand_cycle
	                              && !_cpuAS && !fpu_active_phase;
	wire eff_fpu_dsack0_n = fpu_inactive_phase_act ? 1'b0 : fpu_dsack0_n;
	wire eff_fpu_dsack1_n = fpu_inactive_phase_act ? 1'b1 : fpu_dsack1_n;
	// TG68K read mux:
	//  - Non-Operand: FPU's d_out[15:0] (16-bit response/save/etc).
	//  - Operand phase=0: HIGH word direct from FPU's d_out[31:16].
	//  - Operand phase=1: LOW word from the latch.
	wire [15:0] fpu_d_to_cpu = fpu_is_operand_cycle
	                           ? (fpu_xfer_phase ? fpu_rd_latch[15:0]
	                                             : fpu_data_out[31:16])
	                           : fpu_data_out[15:0];
	// Size encoding: derive from longword + UDS/LDS.
	wire [1:0] fpu_size_n =
	    _cpuAS                     ? 2'b11 :  // idle
	    tg68_longword              ? 2'b00 :  // .L
	    (!_cpuUDS && !_cpuLDS)     ? 2'b10 :  // .W
	                                 2'b01;   // .B

`ifdef USE_FPU_STUB
	// CIR-protocol no-op stub (Makefile: USE_FPU_STUB=1). Accepts writes,
	// always returns "done". Doesn't compute anything; useful when running
	// non-FPU software and skipping FPU area/runtime cost.
	sim_fpu_cir_stub fpu_inst (
		.clk          ( clk_sys              ),
		.reset_n      ( _cpuReset            ),
		.a_in         ( cpuAddr[5:1]         ),  // stub doesn't need remap
		.d_in         ( fpu_d_in_eff         ),
		.d_out        ( fpu_data_out         ),
		.size_n       ( fpu_size_n           ),
		.as_n         ( _cpuAS               ),
		.cs_n         ( fpu_cs_n_eff         ),
		.rw           ( _cpuRW               ),
